namespace {
[[noreturn]] void refuse(const std::string& m) { throw nxr::io::Error(code::invalid_argument, m); }

constexpr double kTwoPi = 6.283185307179586476925286766559;

std::uint64_t mix(std::uint64_t z) {   // splitmix64's finaliser
  z += 0x9e3779b97f4a7c15ULL;
  z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ULL;
  z = (z ^ (z >> 27)) * 0x94d049bb133111ebULL;
  return z ^ (z >> 31);
}
// a uniform in (0, 1) keyed by four numbers
double uniform(std::uint64_t seed, std::uint64_t a, std::uint64_t b, std::uint64_t c) {
  const std::uint64_t h = mix(mix(mix(mix(seed) ^ a) ^ b) ^ c);
  return (static_cast<double>(h >> 11) + 0.5) / 9007199254740992.0;
}

std::string number(double v) {
  std::ostringstream s;
  s << v;
  return s.str();
}

void check(const SyntheticRecording& o) {
  if (o.n_channels < 1 || o.n_channels > 4096) refuse("--channels must be from 1 to 4096");
  if (!(o.sfreq > 0) || o.sfreq > 1e5) refuse("--sfreq must be above 0 and at most 100000 Hz");
  if (!(o.duration > 0)) refuse("--duration must be above 0 seconds");
  const double n = std::round(o.sfreq * o.duration);
  if (n < 1) refuse("--sfreq and --duration make no sample");
  if (n * static_cast<double>(o.n_channels) > 2e9) refuse("the recording would hold more than 2e9 values (channels x samples); make it shorter");
  for (double f : o.frequencies) if (!(f > 0) || !(f < o.sfreq / 2)) refuse("each frequency must be above 0 and below half the sampling rate (" + number(o.sfreq / 2) + " Hz)");
  if (o.amplitude < 0 || o.noise < 0) refuse("--amplitude and --noise cannot be negative");
}

class SyntheticReader final : public nxr::formats::RecordingReader {
 public:
  explicit SyntheticReader(const SyntheticRecording& o) : o_(o) {
    h_.format = "synthetic";
    h_.sampling_rate = o.sfreq;
    h_.n_samples = static_cast<std::uint64_t>(std::llround(o.sfreq * o.duration));
    h_.precision = nxr::formats::Precision::float32;
    for (std::int64_t c = 0; c < o.n_channels; ++c) {
      nxr::formats::Channel ch;
      char buf[16];
      std::snprintf(buf, sizeof buf, "EEG %03lld", static_cast<long long>(c + 1));
      ch.name = buf;
      ch.kind = "eeg";
      ch.unit = "V";
      ch.file_unit = "V";
      ch.sampling_rate = o.sfreq;
      h_.channels.push_back(ch);
    }
    for (std::int64_t c = 0; c < o.n_channels; ++c)
      for (std::size_t k = 0; k < o.frequencies.size(); ++k) phase_.push_back(kTwoPi * uniform(o.seed, static_cast<std::uint64_t>(c), k, 0));
  }
  const nxr::formats::RecordingHeader& header() const override { return h_; }
  void read(std::uint64_t s0, std::uint64_t n, std::size_t c0, std::size_t c1, float* out) const override {
    check_range(s0, n, c0, c1);
    const std::size_t K = o_.frequencies.size();
    for (std::size_t c = c0; c < c1; ++c)
      for (std::uint64_t j = 0; j < n; ++j) {
        const std::uint64_t i = s0 + j;
        double x = 0;
        for (std::size_t k = 0; k < K; ++k)
          x += o_.amplitude / static_cast<double>(k + 1) * std::sin(kTwoPi * o_.frequencies[k] * static_cast<double>(i) / o_.sfreq + phase_[c * K + k]);
        if (o_.noise > 0) {
          const double u1 = uniform(o_.seed, c, i, 1), u2 = uniform(o_.seed, c, i, 2);
          x += o_.noise * std::sqrt(-2.0 * std::log(u1)) * std::cos(kTwoPi * u2);   // Box-Muller
        }
        out[(c - c0) * n + j] = static_cast<float>(x);
      }
  }

 private:
  SyntheticRecording o_;
  nxr::formats::RecordingHeader h_;
  std::vector<double> phase_;   // [channel x frequency]
};
}  // namespace

std::unique_ptr<nxr::formats::RecordingReader> synthetic_reader(const SyntheticRecording& opt) {
  check(opt);
  return std::make_unique<SyntheticReader>(opt);
}

std::string synthetic_description(const SyntheticRecording& o) {
  std::string f;
  for (double v : o.frequencies) f += (f.empty() ? "" : ",") + number(v);
  return "seed=" + std::to_string(o.seed) + ";channels=" + std::to_string(o.n_channels) + ";sfreq=" + number(o.sfreq) + ";duration=" + number(o.duration) + ";frequencies=" + f +
         ";amplitude=" + number(o.amplitude) + ";noise=" + number(o.noise);
}

Json create_synthetic(nxr::io::DatasetWriter& w, nxr::io::SubjectWriter& sub, const SyntheticRecording& o) {
  const auto reader = synthetic_reader(o);
  RecordingImport ri;
  ri.name = o.name;
  ri.acquisition = o.acquisition;
  ri.format = "synthetic";
  ri.source = synthetic_description(o);
  ri.licence = "CC0-1.0";
  ri.attribution = "generated by nxr-neuro";
  ri.redistributable = true;
  ri.extra = Json{{"synthetic", Json{{"seed", o.seed}, {"frequencies", o.frequencies}, {"amplitude", o.amplitude}, {"noise", o.noise}}}};
  ri.progress = o.progress;
  return import_recording(w, sub, *reader, ri);
}

