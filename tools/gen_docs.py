#!/usr/bin/env python3
"""Generate the reference pages that are read off the code, never written by hand.

  docs/pipelines/<name>.md   one page per YAML definition in pipelines/definitions
  docs/pipelines/README.md   the index of those pages
  docs/nodes.md              every registered node (read from `nxr-neuro list pipelines --json`)

Usage:
  python3 tools/gen_docs.py [--binary PATH_TO_nxr-neuro] [--nodes-json FILE] [--check]

The definitions are read with PyYAML. The node registry is read from the command's own JSON listing
(`nxr-neuro list pipelines --json`, field "steps"), either by running a built binary (--binary, default
build/cli/nxr-neuro) or from a saved listing (--nodes-json). With --check nothing is written; the exit status is 1
when a generated file is out of date.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

class Loader(yaml.SafeLoader):
    """YAML 1.2 booleans: `on` and `off` are names (e.g. an output's `on:`), only true and false are booleans."""


Loader.yaml_implicit_resolvers = {
    k: [(t, r) for t, r in v if t != "tag:yaml.org,2002:bool"] for k, v in yaml.SafeLoader.yaml_implicit_resolvers.items()
}
Loader.add_implicit_resolver("tag:yaml.org,2002:bool", re.compile(r"^(?:true|false)$"), list("tf"))

ROOT = Path(__file__).resolve().parent.parent
DEFS = ROOT / "pipelines" / "definitions"
OUT = ROOT / "docs"
HEADER = "<!-- generated by tools/gen_docs.py; edit the YAML (pipelines/definitions/%s), not this page -->\n\n"
NODES_HEADER = "<!-- generated by tools/gen_docs.py from the node registry (`nxr-neuro list pipelines --json`); edit the node's registration, not this page -->\n\n"


def cell(x):
    """A value as a table cell."""
    if x is None:
        return "none"
    if isinstance(x, bool):
        return "true" if x else "false"
    s = json.dumps(x) if isinstance(x, (list, dict)) else str(x)
    return "`%s`" % s.replace("|", "\\|") if s != "" else "``"


def text(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def header_comment(path):
    """The leading '#' block of a definition (its design notes), with internal dates dropped."""
    lines = []
    for ln in path.read_text().splitlines():
        if not ln.startswith("#"):
            break
        lines.append(re.sub(r"\s*\(20\d\d-\d\d-\d\d[^)]*\)", "", ln.lstrip("#").rstrip()))
    return "\n".join(l[1:] if l.startswith(" ") else l for l in lines).strip()


def usage_lines(note):
    return [l.strip() for l in note.splitlines() if re.match(r"\s*nxr-neuro run ", l)]


def flatten_steps(steps):
    """(phase, step) pairs, phases in the order before / chunks / after."""
    out = []
    for phase in ("before", "chunks", "after"):
        s = (steps or {}).get(phase)
        if s is None:
            continue
        items = s.get("do", []) if isinstance(s, dict) else s
        over = s.get("over") if isinstance(s, dict) else None
        for st in items:
            out.append((phase, over, st))
    for phase, s in (steps or {}).items():
        if phase not in ("before", "chunks", "after"):
            items = s.get("do", []) if isinstance(s, dict) else s
            for st in items:
                out.append((phase, None, st))
    return out


def dashed(name):
    return "--" + name.replace("_", "-")


def pipeline_page(path):
    d = yaml.load(path.read_text(), Loader=Loader)
    name = d["pipeline"]
    note = header_comment(path)
    o = [HEADER % path.name, "# `%s`\n" % name, "%s.\n" % str(d.get("description", "")).rstrip(".")]
    o.append("Version %s, scope `%s`. Run it with `nxr-neuro run %s --dataset <folder> --subject <id> ...`; "
             "`nxr-neuro run %s --help` prints the same options.\n" % (d.get("version"), d.get("scope"), name, name))
    u = usage_lines(note)
    if u:
        o.append("Examples:\n\n```\n%s\n```\n" % "\n".join(u))
    o.append("## Inputs\n")
    ins = d.get("inputs") or {}
    if ins:
        o.append("| input | what it is | required |\n|---|---|---|")
        for k, v in ins.items():
            kind = next((x for x in ("field", "selection", "statistic", "measurement", "kernel", "surface") if x in v), "")
            what = ", ".join("%s %s" % (a, json.dumps(b) if not isinstance(b, str) else b) for a, b in v.items() if a not in ("hint",))
            hint = v.get("hint")
            req = "no" if v.get("required") is False else "yes"
            o.append("| `%s` | %s%s | %s |" % (k, text(what), " (%s)" % text(hint) if hint else "", req))
        o.append("")
    else:
        o.append("None: the pipeline reads nothing stored.\n")
    o.append("## Parameters\n")
    params = d.get("parameters") or {}
    if params:
        o.append("Each is an option `--<name> VALUE` (dashes for underscores; the value is read as YAML) or `--set NAME=VALUE`.\n")
        o.append("| parameter | option | default | unit | choices | meaning |\n|---|---|---|---|---|---|")
        for k, v in params.items():
            ch = ", ".join(str(c) for c in v["choices"]) if v.get("choices") else ""
            o.append("| `%s` | `%s` | %s | %s | %s | %s |" % (k, dashed(k), cell(v.get("default")), text(v.get("unit", "")), text(ch), text(v.get("meaning", ""))))
        o.append("")
    else:
        o.append("None.\n")
    pres = d.get("presets") or {}
    if pres:
        o.append("## Presets\n")
        o.append("`--set <preset>` sets the parameters below at once; a parameter given by name wins over the preset.\n")
        o.append("| preset | sets |\n|---|---|")
        for k, v in pres.items():
            o.append("| `%s` | %s |" % (k, text(", ".join("%s=%s" % (a, json.dumps(b) if not isinstance(b, str) else b) for a, b in v.items()))))
        o.append("")
    o.append("## The chain of nodes\n")
    st = flatten_steps(d.get("steps"))
    if st:
        o.append("| phase | node | in | with | out |\n|---|---|---|---|---|")
        for phase, over, s in st:
            ph = phase + (" over `%s`" % over if over else "")
            node = s.get("node", s.get("step", "?"))
            ins_ = ", ".join("%s=%s" % (a, b) for a, b in (s.get("in") or {}).items())
            wi = ", ".join("%s=%s" % (a, json.dumps(b) if not isinstance(b, str) else b) for a, b in (s.get("with") or {}).items())
            out = s.get("out")
            out = ", ".join(out) if isinstance(out, list) else (out or "")
            o.append("| %s | [`%s`](../nodes.md) | %s | %s | %s |" % (ph, node, text(ins_), text(wi), text(out)))
        o.append("\n`before` steps run once, `chunks` steps run on every chunk of the recording, `after` steps run once on what the chunks accumulated.\n")
    else:
        o.append("The pipeline is a single built-in computation.\n")
    o.append("## Outputs\n")
    outs = d.get("outputs") or {}
    if outs:
        o.append("| output | stored as |\n|---|---|")
        for k, v in outs.items():
            o.append("| `%s` | %s |" % (k, text(", ".join("%s %s" % (a, json.dumps(b) if not isinstance(b, str) else b) for a, b in v.items()))))
        o.append("")
    else:
        o.append("None declared.\n")
    if note:
        o.append("## Notes from the definition\n")
        o.append("```text\n%s\n```\n" % note)
    return name, str(d.get("description", "")).rstrip("."), "\n".join(o)


def load_nodes(binary, nodes_json):
    if nodes_json:
        raw = Path(nodes_json).read_text()
    else:
        raw = subprocess.run([binary, "list", "pipelines", "--json"], check=True, capture_output=True, text=True).stdout
    for ln in raw.splitlines():
        d = json.loads(ln)
        if "steps" in d:
            return d["steps"]
    sys.exit("no node listing found")


KIND = {
    "setup": "setup: runs once, before the data flows",
    "chunk": "chunk: runs on every block of every chunk",
    "accumulate": "accumulate: folds each chunk into a running result",
    "array": "array: runs once on whole arrays",
    "after": "after: runs once on the accumulated result",
}


def nodes_page(nodes):
    o = [NODES_HEADER, "# Nodes\n",
         "Every node a pipeline can use: a pure function of the data handed to it, with named input and output ports. Pipelines (see the [index](pipelines/README.md)) "
         "are chains of these nodes. The toolbox is the part of the name before the dot.\n"]
    kinds = sorted({n["kind"] for n in nodes})
    o.append("Kinds: " + "; ".join(KIND.get(k, k) for k in kinds) + ".\n")
    tb = {}
    for n in nodes:
        tb.setdefault(n["name"].split(".")[0], []).append(n)
    o.append("Toolboxes: " + ", ".join("[%s](#%s) (%d)" % (t, t, len(v)) for t, v in sorted(tb.items())) + ".\n")
    for t, v in sorted(tb.items()):
        o.append("## %s\n" % t)
        o.append("| node | kind | inputs (optional marked) | outputs | parameters (defaults) | what it does |\n|---|---|---|---|---|---|")
        for n in sorted(v, key=lambda n: n["name"]):
            opt = set(n.get("optional", []))
            ins = ", ".join("`%s`%s" % (i, "?" if i in opt else "") for i in n["inputs"])
            outs = ", ".join("`%s`" % i for i in n["outputs"])
            ps = ", ".join("`%s`=%s" % (k, cell(x)[0:] if not isinstance(x, str) else "`%s`" % x) for k, x in n["parameters"].items())
            desc = n.get("description", "")
            m = n.get("matches")
            if m:
                desc += " Matches: %s" % m
            o.append("| `%s` | %s | %s | %s | %s | %s |" % (n["name"], n["kind"], ins, outs, text(ps).replace("``", "`"), text(desc)))
        o.append("")
    return "\n".join(o)


def index_page(rows):
    o = ["<!-- generated by tools/gen_docs.py; edit the YAML in pipelines/definitions, not this page -->\n",
         "# Pipelines\n",
         "Every pipeline `nxr-neuro run <name>` knows, one page each: what it measures, its inputs, every parameter with its meaning, default and unit, its presets, "
         "the chain of nodes it runs and what it stores. The nodes are described in [../nodes.md](../nodes.md); the method behind each is in [../reference.md](../reference.md).\n",
         "| pipeline | what it does |\n|---|---|"]
    for name, desc, _ in rows:
        o.append("| [`%s`](%s.md) | %s |" % (name, name, text(desc)))
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--binary", default=str(ROOT / "build" / "cli" / "nxr-neuro"))
    ap.add_argument("--nodes-json")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = {}
    rows = []
    for p in sorted(DEFS.glob("*.yaml")):
        name, desc, page = pipeline_page(p)
        rows.append((name, desc, page))
        files[OUT / "pipelines" / (name + ".md")] = page + "\n"
    files[OUT / "pipelines" / "README.md"] = index_page(rows)
    files[OUT / "nodes.md"] = nodes_page(load_nodes(a.binary, a.nodes_json)) + "\n"
    stale = 0
    for f, c in files.items():
        if a.check:
            if not f.exists() or f.read_text() != c:
                print("out of date:", f.relative_to(ROOT))
                stale += 1
        else:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(c)
    if a.check:
        sys.exit(1 if stale else 0)
    print("wrote %d files" % len(files))


if __name__ == "__main__":
    main()
