#!/usr/bin/env python3
"""Generate io/include/nxr/io/records/rows.h: one row struct per table of io/schema/model.sql.

    python3 tools/gen_record_rows.py            write the header
    python3 tools/gen_record_rows.py --check    fail (exit 1) when the header on disk is not what the schema gives (the io test `records_rows_current`)

Each struct has the table's columns in the table's order, named as the columns are named. A NOT NULL column is a plain member, a nullable column a
`std::optional`; INTEGER is `std::int64_t`, REAL `double`, TEXT `std::string`, a `*_json` column `Json` (JSON null: the column is NULL), and a `status`
column the enum `Status`. Every struct has `from_row(const Row&)` (a database row), `from_json`/`to_json` (keys are the column names: the Studio's row
objects) and `columns()`. The generator reads only `CREATE TABLE` statements; the views and triggers are not rows.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "io" / "schema" / "model.sql"
OUT = ROOT / "io" / "include" / "nxr" / "io" / "records" / "rows.h"


def strip_comments(sql: str) -> str:
    return re.sub(r"--[^\n]*", "", sql)


def split_top(body: str):
    parts, depth, cur, quote = [], 0, "", False
    for ch in body:
        if ch == "'":
            quote = not quote
        if not quote:
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == "," and depth == 0:
                parts.append(cur.strip())
                cur = ""
                continue
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def tables(sql: str):
    sql = strip_comments(sql)
    for m in re.finditer(r"CREATE TABLE (\w+) \(", sql):
        i, depth = m.end(), 1
        while depth:
            c = sql[i]
            depth += (c == "(") - (c == ")")
            i += 1
        body = sql[m.end(): i - 1]
        cols = []
        for part in split_top(body):
            w = part.split()
            if w[0] in ("PRIMARY", "UNIQUE", "CHECK", "FOREIGN", "CONSTRAINT"):
                continue
            name, typ = w[0], w[1].upper() if len(w) > 1 else "TEXT"
            rest = part.upper()
            notnull = "NOT NULL" in rest or "PRIMARY KEY" in rest
            if name == "status" and "'deleting'" in part:
                typ = "STATUS"
            cols.append((name, typ, notnull))
        yield m.group(1), cols


CPP_TYPE = {"TEXT": "std::string", "INTEGER": "std::int64_t", "REAL": "double", "BLOB": "std::string", "ANY": "Value"}


KEYWORDS = {"operator", "default", "class", "new", "delete", "template", "namespace", "register", "union", "enum", "private", "public", "this", "case", "switch", "inline"}


def mem(name: str) -> str:
    """the member's name: the column's, with `_` after a C++ keyword (`operator_`)"""
    return name + "_" if name in KEYWORDS else name


def struct_name(table: str) -> str:
    return "".join(p.capitalize() for p in table.split("_")) + "Row"


def member(name, typ, notnull):
    if typ == "STATUS":
        return "Status", False
    if name.endswith("_json"):
        return "Json", False
    base = CPP_TYPE[typ]
    return (base if notnull else f"std::optional<{base}>"), True


def gen() -> str:
    out = []
    out.append("""// GENERATED by tools/gen_record_rows.py from io/schema/model.sql: DO NOT EDIT. One row struct per table, columns in the table's order.
// NOT NULL: a plain member; nullable: std::optional; a `*_json` column: Json (null = SQL NULL); `status`: the enum Status.
// `from_row` reads a database row, `from_json`/`to_json` use the column names as keys (the Studio's row objects).
#pragma once
#include <cstdint>
#include <optional>
#include <string>
#include <vector>

#include "nxr/io/database.h"
#include "nxr/io/errors.h"
#include "nxr/io/json_text.h"

namespace nxr::io::records {

enum class Status { pending, complete, deleting };
const char* to_string(Status s);
Status status_from(const std::string& s);

namespace detail {
template <class T> T take(const Row& r, const char* c);
template <> inline std::string take<std::string>(const Row& r, const char* c) { return text(r, c); }
template <> inline std::int64_t take<std::int64_t>(const Row& r, const char* c) {
  auto it = r.find(c);
  if (it == r.end()) return 0;
  if (auto* i = std::get_if<std::int64_t>(&it->second)) return *i;
  if (auto* d = std::get_if<double>(&it->second)) return static_cast<std::int64_t>(*d);
  return 0;
}
template <> inline double take<double>(const Row& r, const char* c) {
  auto it = r.find(c);
  if (it == r.end()) return 0;
  if (auto* d = std::get_if<double>(&it->second)) return *d;
  if (auto* i = std::get_if<std::int64_t>(&it->second)) return static_cast<double>(*i);
  return 0;
}
template <> inline Value take<Value>(const Row& r, const char* c) { auto it = r.find(c); return it == r.end() ? Value{} : it->second; }
template <class T> std::optional<T> take_opt(const Row& r, const char* c) {
  auto it = r.find(c);
  if (it == r.end() || is_null(it->second)) return std::nullopt;
  return take<T>(r, c);
}
inline Json take_json(const Row& r, const char* c) {
  auto it = r.find(c);
  if (it == r.end() || is_null(it->second)) return Json();
  return Json::parse(text(r, c));
}
template <class T> void put(Json& j, const char* c, const T& v) { j[c] = v; }
template <class T> void put(Json& j, const char* c, const std::optional<T>& v) { j[c] = v ? Json(*v) : Json(); }
inline void put(Json& j, const char* c, const Value& v) {
  if (auto* i = std::get_if<std::int64_t>(&v)) j[c] = *i;
  else if (auto* d = std::get_if<double>(&v)) j[c] = *d;
  else if (auto* s = std::get_if<std::string>(&v)) j[c] = *s;
  else j[c] = Json();
}
inline void put(Json& j, const char* c, Status v) { j[c] = to_string(v); }
inline void put_json(Json& j, const char* c, const Json& v) { j[c] = v; }
template <class T> T get(const Json& j, const char* c, const T& dflt = T()) {
  if (!j.contains(c) || j[c].is_null()) return dflt;
  return j[c].get<T>();
}
template <class T> std::optional<T> get_opt(const Json& j, const char* c) {
  if (!j.contains(c) || j[c].is_null()) return std::nullopt;
  return j[c].get<T>();
}
inline Json get_json(const Json& j, const char* c) { return j.contains(c) ? j[c] : Json(); }
}  // namespace detail
""")
    for table, cols in tables(MODEL.read_text()):
        s = struct_name(table)
        out.append(f"// table `{table}`\nstruct {s} {{")
        for name, typ, nn in cols:
            t, _ = member(name, typ, nn)
            dflt = " = Status::complete" if typ == "STATUS" else ""
            out.append(f"  {t} {mem(name)}{dflt};")
        out.append(f"  static constexpr const char* kTable = \"{table}\";")
        out.append("  static const std::vector<std::string>& columns() {")
        out.append("    static const std::vector<std::string> c = {" + ", ".join(f'"{n}"' for n, _, _ in cols) + "};")
        out.append("    return c;\n  }")
        out.append(f"  static {s} from_row(const Row& r) {{\n    {s} x;")
        for name, typ, nn in cols:
            if typ == "STATUS":
                out.append(f'    x.status = status_from(text(r, "status"));')
            elif name.endswith("_json"):
                out.append(f'    x.{mem(name)} = detail::take_json(r, "{name}");')
            elif nn:
                out.append(f'    x.{mem(name)} = detail::take<{CPP_TYPE[typ]}>(r, "{name}");')
            else:
                out.append(f'    x.{mem(name)} = detail::take_opt<{CPP_TYPE[typ]}>(r, "{name}");')
        out.append("    return x;\n  }")
        out.append(f"  static {s} from_json(const Json& j) {{\n    {s} x;")
        for name, typ, nn in cols:
            if typ == "STATUS":
                out.append(f'    x.status = status_from(detail::get<std::string>(j, "status", "complete"));')
            elif name.endswith("_json"):
                out.append(f'    x.{mem(name)} = detail::get_json(j, "{name}");')
            elif nn:
                out.append(f'    x.{mem(name)} = detail::get<{CPP_TYPE[typ]}>(j, "{name}");')
            else:
                out.append(f'    x.{mem(name)} = detail::get_opt<{CPP_TYPE[typ]}>(j, "{name}");')
        out.append("    return x;\n  }")
        out.append("  Json to_json() const {\n    Json j = Json::object();")
        for name, typ, nn in cols:
            fn = "put_json" if name.endswith("_json") else "put"
            out.append(f'    detail::{fn}(j, "{name}", {mem(name)});')
        out.append("    return j;\n  }\n};\n")
    out.append("}  // namespace nxr::io::records\n")
    return "\n".join(out)


def main():
    text = gen()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is not current: run tools/gen_record_rows.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
